/// Which Firebase project this build talks to, decided at COMPILE time.
///
/// Fail closed on purpose. There is no default: a build that does not name an
/// environment throws at startup rather than quietly choosing production. The
/// Gradle side refuses to package such a build at all (see
/// android/app/build.gradle.kts), so this is the second of two gates.
///
/// Pair the Dart define with the matching Gradle flavour - they select
/// different halves of the same app:
///
///   flutter run --flavor dev  --dart-define=FIREBASE_ENV=dev
///   flutter run --flavor prod --dart-define=FIREBASE_ENV=prod
///
/// [assertResolvedProject] catches the case where someone pairs them wrongly.
library;

import 'package:firebase_core/firebase_core.dart';
import 'firebase_options.dart';

/// Environments this app knows how to talk to.
enum FirebaseEnv {
  dev('dev', 'alehulsh-dev'),
  prod('prod', 'alehulsh-app');

  const FirebaseEnv(this.defineValue, this.projectId);

  /// Value passed as --dart-define=FIREBASE_ENV=...
  final String defineValue;

  /// The project this environment MUST resolve to at runtime.
  final String projectId;
}

const String _rawEnv = String.fromEnvironment('FIREBASE_ENV');

/// The selected environment, or null when none was named.
FirebaseEnv? get selectedEnvOrNull {
  for (final env in FirebaseEnv.values) {
    if (env.defineValue == _rawEnv) return env;
  }
  return null;
}

/// The selected environment. Throws rather than guessing.
FirebaseEnv get selectedEnv {
  final env = selectedEnvOrNull;
  if (env == null) {
    throw StateError(
      _rawEnv.isEmpty
          ? 'FIREBASE_ENV was not set. Build with '
              '--dart-define=FIREBASE_ENV=dev or =prod. Refusing to assume '
              'production.'
          : 'FIREBASE_ENV="$_rawEnv" is not a known environment. '
              'Expected one of: ${FirebaseEnv.values.map((e) => e.defineValue).join(', ')}.',
    );
  }
  return env;
}

/// Options for the selected environment.
///
/// The dev project's generated options file does not exist yet. Until it does,
/// selecting dev throws with the command that creates it - never a silent
/// fallback to production.
FirebaseOptions optionsForSelectedEnv() {
  switch (selectedEnv) {
    case FirebaseEnv.prod:
      return DefaultFirebaseOptions.currentPlatform;
    case FirebaseEnv.dev:
      // Replace with DevFirebaseOptions.currentPlatform once generated by:
      //   flutterfire configure --project=alehulsh-dev \
      //     --out=lib/firebase_options_dev.dart
      throw StateError(
        'FIREBASE_ENV=dev but lib/firebase_options_dev.dart has not been '
        'generated yet. Run: flutterfire configure --project=alehulsh-dev '
        '--out=lib/firebase_options_dev.dart . Refusing to fall back to '
        'production.',
      );
  }
}

/// Verify the project Firebase ACTUALLY resolved matches the one selected.
///
/// The configured options and the project that ends up in use are not the same
/// thing: on Android the google-services plugin initialises the default app
/// from google-services.json before Dart runs, so a stale or mismatched file
/// wins over anything declared here. Reading [FirebaseApp.options] after
/// initialisation is the only way to know which project is really in play.
///
/// Throws on disagreement. A test build pointed at production is the exact
/// accident this whole mechanism exists to prevent.
void assertResolvedProject(FirebaseApp app) {
  final resolved = app.options.projectId;
  final expected = selectedEnv.projectId;
  if (resolved != expected) {
    throw StateError(
      'Firebase project mismatch: selected ${selectedEnv.defineValue} expects '
      '"$expected" but the app resolved "$resolved". The Gradle flavour and '
      '--dart-define=FIREBASE_ENV disagree, or google-services.json is stale. '
      'Refusing to continue.',
    );
  }
}
